-- Execute no SQL Editor do Supabase.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(10,2) not null check (price > 0),
  description text default '',
  image_url text,
  available boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;

-- Leitura pública: clientes só enxergam produtos disponíveis.
drop policy if exists "Public can read available products" on public.products;
create policy "Public can read available products" on public.products
for select to anon, authenticated using (available = true);

-- Lista de administradores autorizados.
create table if not exists public.store_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.store_admins enable row level security;

drop policy if exists "Admins can read admin list" on public.store_admins;
create policy "Admins can read admin list" on public.store_admins
for select to authenticated using (auth.uid() = user_id);

-- Somente usuários cadastrados em store_admins podem gerenciar produtos.
drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products" on public.products
for all to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.store_admins a where a.user_id = auth.uid()));

